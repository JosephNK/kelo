#!/usr/bin/env node
// =============================================================================
// Writes <output-dir>/ARCHITECTURE.md — the project folder tree extracted from
// rules/<framework>/base/lint-rules-structure-reference.md (generated from the
// lint boundary elements, so the documented layout is the enforced layout).
//
// Usage:
//   gen-architecture.mjs <framework> -p <output-dir>
// =============================================================================

import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { ensureGitRepo, normalizePath } from "./common.mjs";

const HELP = `Usage: gen-architecture.mjs <framework> -p <output-dir>

Writes ARCHITECTURE.md (folder tree enforced by lint) to the output directory.

Arguments:
  <framework>    Framework name (e.g. nextjs, nestjs, flutter)

Options:
  -p <dir>       Output directory (required)
  -h, --help     Show this help

Examples:
  ./scripts/gen-architecture.mjs nextjs -p ./my-project
  ./scripts/gen-architecture.mjs nestjs -p ./my-project
`;

function usage(code = 1) {
  (code === 0 ? process.stdout : process.stderr).write(HELP);
  process.exit(code);
}

function parseArgs(argv) {
  const args = { framework: "", outputDir: "" };
  const rest = argv.slice(2);

  if (rest.length >= 1 && !rest[0].startsWith("-")) {
    args.framework = rest.shift();
  }

  while (rest.length > 0) {
    const a = rest.shift();
    switch (a) {
      case "-p":
        if (!rest.length) {
          process.stderr.write("-p requires a directory\n");
          usage();
        }
        args.outputDir = rest.shift();
        break;
      case "-h":
      case "--help":
        usage(0);
        break;
      default:
        process.stderr.write(`Unknown option: ${a}\n`);
        usage();
    }
  }

  if (!args.framework) {
    process.stderr.write("Error: framework is required\n");
    usage();
  }
  if (!args.outputDir) {
    process.stderr.write("Error: -p <output-dir> is required\n");
    usage();
  }

  return args;
}

function main() {
  const args = parseArgs(process.argv);

  // ARCHITECTURE.md is a project-level doc; refuse to write it from a random dir.
  try {
    ensureGitRepo(".");
  } catch (err) {
    process.stderr.write(`Error: ${err.message}\n`);
    process.exit(1);
  }

  fs.mkdirSync(args.outputDir, { recursive: true });

  let outputDir;
  try {
    outputDir = normalizePath(args.outputDir);
  } catch (err) {
    process.stderr.write(`Error: ${err.message}\n`);
    process.exit(1);
  }

  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const pluginRoot = path.resolve(scriptDir, "..");
  const source = path.join(
    pluginRoot,
    "rules",
    args.framework,
    "base",
    "lint-rules-structure-reference.md",
  );

  if (!fs.existsSync(source)) {
    process.stderr.write(`Error: Structure reference not found: ${source}\n`);
    process.exit(1);
  }

  // "## 프로젝트 구조" 섹션(안내문 + 트리)만 가져온다
  const text = fs.readFileSync(source, "utf8");
  const start = text.indexOf("## 프로젝트 구조\n");
  if (start < 0) {
    process.stderr.write(
      `Error: '## 프로젝트 구조' section not found in ${source}\n`,
    );
    process.exit(1);
  }
  const bodyStart = start + "## 프로젝트 구조\n".length;
  const next = text.indexOf("\n## ", bodyStart);
  const body = text.slice(bodyStart, next < 0 ? undefined : next).trim();

  const outputFile = path.join(outputDir, "ARCHITECTURE.md");
  fs.writeFileSync(
    outputFile,
    [
      "<!-- GENERATED BY kelo (/kelo:setup) — DO NOT MODIFY BY HAND -->",
      "",
      "# Architecture",
      "",
      "이 폴더 구조는 lint(아키텍처 경계 규칙)로 강제된다. 새 파일은 아래 위치·이름에 맞춰 만든다. 트리의 주석은 레이어(type) — 설명이다.",
      "",
      body,
      "",
    ].join("\n"),
  );

  process.stdout.write(`Generated: ${outputFile}\n`);
}

main();
